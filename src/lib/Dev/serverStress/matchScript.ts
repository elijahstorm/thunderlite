/**
 * A real match, reduced to the shape of the load it put on the server.
 *
 * Derived from match 24 (2026-09-02, 2 humans + 2 CPU seats, 21.9 minutes, 622
 * actions in 375 relays, 60 turns). Each row is one relay the server received:
 * when it arrived relative to the first action, which human client sent it, and
 * the seat and kind of every action it carried. Tiles, paths and unit types are
 * gone on purpose: the server never simulates, so what it costs to store an
 * action does not depend on what the action was, only on how many arrive, how
 * they batch, and how far apart they land.
 *
 * Seats are tagged `h` (host, seat 0), `g` (guest, seat 1), `a` and `b` (the two
 * CPU seats the host drove). The guest surrendered four minutes in, after which
 * every relay is the host driving three sides. That is the worst shape a room
 * takes for the gateway budget, which is why this match and not a gentler one.
 *
 * The simulator does not replay these seat tags literally. Whose turn it is comes
 * from the room the simulator actually created, so the tags only decide whether
 * a relay belongs to the guest (before its surrender) or to the host; the rest is
 * timing and batch shape. See `simulator.server.ts`.
 *
 * Action kinds over the match: move 206, wait 170, attack 88, end-turn 60,
 * build 56, repair 30, transport-unload 11, surrender 1.
 */

